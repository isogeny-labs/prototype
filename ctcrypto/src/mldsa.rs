/// Algorithm 6 ML-DSA.KeyGen_internal(xi). Returns (pk, sk).
///
/// `xi` is the caller's 32-byte secret seed. The secret key output must be
/// protected (and wiped) by the caller.
pub fn keygen_internal(xi: &[u8; 32]) -> ([u8; PK_LEN], [u8; SK_LEN]) {
    let mut seed = [0u8; 128];
    {
        let mut h = Sponge::shake256();
        h.absorb(xi);
        h.absorb(&[K as u8, L as u8]);
        h.squeeze(&mut seed);
    }
    let mut rho = [0u8; 32];
    rho.copy_from_slice(&seed[..32]);
    // DECLASSIFY (keygen rho): rho is the public matrix seed; FIPS 204 places
    // it verbatim in the public key. ExpandA branches on it.
    ct::declassify(&mut rho);
    let mut rho_p = [0u8; 64];
    rho_p.copy_from_slice(&seed[32..96]);
    let mut key = [0u8; 32];
    key.copy_from_slice(&seed[96..128]);
    ct::zeroize(&mut seed);

    let mut s1 = [[0i32; N]; L];
    let mut s2 = [[0i32; N]; K];
    for (r, p) in s1.iter_mut().enumerate() {
        rej_bounded_poly(p, &rho_p, r as u16);
    }
    for (r, p) in s2.iter_mut().enumerate() {
        rej_bounded_poly(p, &rho_p, (L + r) as u16);
    }
    ct::zeroize(&mut rho_p);

    let mut s1_hat = s1;
    for p in s1_hat.iter_mut() {
        ntt(p);
    }
    let mut t = [[0i32; N]; K];
    matvec(&rho, &s1_hat, &mut t);
    ct::zeroize_i32(flat(&mut s1_hat));

    let mut t1 = [[0i32; N]; K];
    for i in 0..K {
        for c in t[i].iter_mut() {
            *c = reduce32(*c);
        }
        invntt_tomont(&mut t[i]);
        for n in 0..N {
            let (a1, a0) = power2round(freeze(t[i][n] + s2[i][n]));
            t1[i][n] = a1;
            t[i][n] = a0; // t now holds t0
        }
    }
    // DECLASSIFY (keygen t1): t1 is the public key (pkEncode(rho, t1)).
    ct::declassify_i32s(flat(&mut t1));

    let mut pk = [0u8; PK_LEN];
    pk[..32].copy_from_slice(&rho);
    for (i, p) in t1.iter().enumerate() {
        let off = 32 + i * POLY_T1_LEN;
        pack_poly(&mut pk[off..off + POLY_T1_LEN], 10, |n| p[n] as u32);
    }
    let tr = tr_of_pk(&pk);

    let mut sk = [0u8; SK_LEN];
    sk[..32].copy_from_slice(&rho);
    sk[32..64].copy_from_slice(&key);
    sk[64..128].copy_from_slice(&tr);
    for (i, p) in s1.iter().enumerate() {
        let off = SK_S1_OFF + i * POLY_ETA_LEN;
        pack_poly(&mut sk[off..off + POLY_ETA_LEN], 3, |n| (ETA - p[n]) as u32);
    }
    for (i, p) in s2.iter().enumerate() {
        let off = SK_S2_OFF + i * POLY_ETA_LEN;
        pack_poly(&mut sk[off..off + POLY_ETA_LEN], 3, |n| (ETA - p[n]) as u32);
    }
    for (i, p) in t.iter().enumerate() {
        let off = SK_T0_OFF + i * POLY_T0_LEN;
        pack_poly(&mut sk[off..off + POLY_T0_LEN], 13, |n| ((1 << (D - 1)) - p[n]) as u32);
    }

    ct::zeroize(&mut key);
    ct::zeroize_i32(flat(&mut s1));
    ct::zeroize_i32(flat(&mut s2));
    ct::zeroize_i32(flat(&mut t));
    (pk, sk)
}

