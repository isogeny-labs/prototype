/// Algorithm 7 ML-DSA.Sign_internal(sk, M', rnd). rnd = [0;32] gives the deterministic variant.
///
/// `m_prime` is the already-formatted message M' (for the pure external
/// interface use [`sign`], which builds `0 || len(ctx) || ctx || M`
/// incrementally).
pub fn sign_internal(sk: &[u8; SK_LEN], m_prime: &[u8], rnd: &[u8; 32]) -> [u8; SIG_LEN] {
    let mu = compute_mu(&sk[64..128], &[m_prime]);
    sign_mu(sk, &mu, rnd)
}

/// Algorithm 2 ML-DSA.Sign (pure, with context; ctx.len() <= 255 else Err(InvalidInput)), randomness supplied by caller.
///
/// HashML-DSA (pre-hash) is not supported. `rnd` must be 32 fresh random
/// bytes for the hedged variant, or all zero for the deterministic variant.
pub fn sign(
    sk: &[u8; SK_LEN],
    msg: &[u8],
    ctx: &[u8],
    rnd: &[u8; 32],
) -> Result<[u8; SIG_LEN], crate::Error> {
    if ctx.len() > 255 {
        return Err(crate::Error::InvalidInput);
    }
    let prefix = [0u8, ctx.len() as u8];
    let mu = compute_mu(&sk[64..128], &[&prefix, ctx, msg]);
    Ok(sign_mu(sk, &mu, rnd))
}

/// ML-DSA.Sign_internal with an externally computed message representative
/// `mu = H(tr || M', 64)` (Algorithm 7 with line 6 done by the caller, the
/// "external mu" option of FIPS 204). [`sign_internal`] and [`sign`] are
/// wrappers around this core.
pub fn sign_mu(sk: &[u8; SK_LEN], mu: &[u8; 64], rnd: &[u8; 32]) -> [u8; SIG_LEN] {
    // --- skDecode -----------------------------------------------------------
    let mut rho = [0u8; 32];
    rho.copy_from_slice(&sk[..32]);
    // DECLASSIFY (sign rho): rho is the public matrix seed, a copy of the
    // first 32 bytes of the public key; ExpandA branches on it.
    ct::declassify(&mut rho);
    let mut key = [0u8; 32];
    key.copy_from_slice(&sk[32..64]);

    let mut s1 = [[0i32; N]; L];
    let mut s2 = [[0i32; N]; K];
    let mut t0 = [[0i32; N]; K];
    for (i, p) in s1.iter_mut().enumerate() {
        let off = SK_S1_OFF + i * POLY_ETA_LEN;
        unpack_poly(&sk[off..off + POLY_ETA_LEN], 3, |n, v| p[n] = ETA - v as i32);
    }
    for (i, p) in s2.iter_mut().enumerate() {
        let off = SK_S2_OFF + i * POLY_ETA_LEN;
        unpack_poly(&sk[off..off + POLY_ETA_LEN], 3, |n, v| p[n] = ETA - v as i32);
    }
    for (i, p) in t0.iter_mut().enumerate() {
        let off = SK_T0_OFF + i * POLY_T0_LEN;
        unpack_poly(&sk[off..off + POLY_T0_LEN], 13, |n, v| p[n] = (1 << (D - 1)) - v as i32);
    }
    for p in s1.iter_mut() {
        ntt(p);
    }
    for p in s2.iter_mut().chain(t0.iter_mut()) {
        ntt(p);
    }

    // rho'' = H(K || rnd || mu, 64)
    let mut rho_pp = [0u8; 64];
    {
        let mut h = Sponge::shake256();
        h.absorb(&key);
        h.absorb(rnd);
        h.absorb(mu);
        h.squeeze(&mut rho_pp);
    }
    ct::zeroize(&mut key);

    let mut y = [[0i32; N]; L];
    let mut z: [Poly; L];
    let mut w = [[0i32; N]; K];
    let mut w1 = [[0i32; N]; K];
    let mut hint = [[0u8; N]; K];
    let mut cp = [0i32; N];
    let mut tmp = [0i32; N];
    let mut w1_buf = [0u8; K * POLY_W1_LEN];
    let mut c_tilde = [0u8; CTILDE_LEN];
    let mut kappa: u16 = 0;

    loop {
        // y = ExpandMask(rho'', kappa); kappa += l
        expand_mask(&mut y, &rho_pp, kappa);
        kappa = kappa.wrapping_add(L as u16);

        // w = NTT^-1(A_hat * NTT(y)), canonical in [0, q)
        z = y;
        for p in z.iter_mut() {
            ntt(p);
        }
        matvec(&rho, &z, &mut w);
        for (wi, w1i) in w.iter_mut().zip(w1.iter_mut()) {
            for c in wi.iter_mut() {
                *c = reduce32(*c);
            }
            invntt_tomont(wi);
            for n in 0..N {
                wi[n] = freeze(wi[n]);
                w1i[n] = decompose(wi[n]).0;
            }
        }

        // c_tilde = H(mu || w1Encode(w1), 64)
        w1_encode(&mut w1_buf, &w1);
        {
            let mut h = Sponge::shake256();
            h.absorb(mu);
            h.absorb(&w1_buf);
            h.squeeze(&mut c_tilde);
        }
        // DECLASSIFY (c_tilde, every attempt): SampleInBall rejection-samples
        // on it. An accepted c_tilde is published in the signature; a rejected
        // attempt's challenge is independent of the key given the abort
        // (standard practice, as in the pqcrystals reference).
        ct::declassify(&mut c_tilde);
        sample_in_ball(&mut cp, &c_tilde);
        ntt(&mut cp);

        // z = y + NTT^-1(c_hat o s1_hat)
        for j in 0..L {
            pointwise(&mut z[j], &cp, &s1[j]);
            invntt_tomont(&mut z[j]);
            for n in 0..N {
                z[j][n] = reduce32(z[j][n] + y[j][n]);
            }
        }
        // DECLASSIFY (||z|| >= gamma1 - beta): the one-bit reject decision,
        // computed over all of z; the number of attempts is public.
        if ct::declassify_u8(norm_exceeds(&z, GAMMA1 - BETA)) != 0 {
            continue;
        }

        // r = w - NTT^-1(c_hat o s2_hat) (canonical, kept in w);
        // r1 = HighBits(r) (kept in w1), r0 = LowBits(r)
        let mut bad = 0u32;
        for i in 0..K {
            pointwise(&mut tmp, &cp, &s2[i]);
            invntt_tomont(&mut tmp);
            for n in 0..N {
                let r = freeze(w[i][n] - tmp[n]);
                let (r1, r0) = decompose(r);
                w[i][n] = r;
                w1[i][n] = r1;
                bad |= mask_abs_ge(r0, GAMMA2 - BETA);
            }
        }
        // DECLASSIFY (||r0|| >= gamma2 - beta): one-bit reject decision over
        // all of r0.
        if ct::declassify_u8((bad & 1) as u8) != 0 {
            continue;
        }

        // ct0 = NTT^-1(c_hat o t0_hat); h = MakeHint(-ct0, r + ct0), i.e.
        // HighBits(r + ct0) != HighBits(r).
        let mut bad = 0u32;
        let mut weight = 0u32;
        for i in 0..K {
            pointwise(&mut tmp, &cp, &t0[i]);
            invntt_tomont(&mut tmp);
            for n in 0..N {
                let ct0 = reduce32(tmp[n]);
                bad |= mask_abs_ge(ct0, GAMMA2);
                let v1 = decompose(freeze(w[i][n] + ct0)).0;
                let hb = ct::mask_nonzero_u32((v1 ^ w1[i][n]) as u32) & 1;
                hint[i][n] = hb as u8;
                weight += hb;
            }
        }
        // DECLASSIFY (||ct0|| >= gamma2): one-bit reject decision over all of ct0.
        if ct::declassify_u8((bad & 1) as u8) != 0 {
            continue;
        }
        // DECLASSIFY (hint weight > omega): one-bit reject decision; the
        // weight itself stays secret here (it becomes public with h below).
        if ct::declassify_u8((ct::mask_lt_u32(OMEGA as u32, weight) & 1) as u8) != 0 {
            continue;
        }
        break;
    }

    // Accepted. DECLASSIFY (signature): z and h are published in sigEncode
    // (c_tilde was declassified above); HintBitPack branches on h.
    ct::declassify_i32s(flat(&mut z));
    for hi in hint.iter_mut() {
        ct::declassify(hi);
    }

    let mut sig = [0u8; SIG_LEN];
    sig[..CTILDE_LEN].copy_from_slice(&c_tilde);
    for (j, p) in z.iter().enumerate() {
        let off = SIG_Z_OFF + j * POLY_Z_LEN;
        pack_poly(&mut sig[off..off + POLY_Z_LEN], 20, |n| (GAMMA1 - p[n]) as u32);
    }
    // Algorithm 20 HintBitPack (h is public now; weight <= omega was checked).
    let mut index = 0;
    for (i, hi) in hint.iter().enumerate() {
        for (n, &b) in hi.iter().enumerate() {
            if b != 0 {
                sig[SIG_H_OFF + index] = n as u8;
                index += 1;
            }
        }
        sig[SIG_H_OFF + OMEGA + i] = index as u8;
    }

    ct::zeroize(&mut rho_pp);
    ct::zeroize(&mut w1_buf);
    ct::zeroize_i32(flat(&mut s1));
    ct::zeroize_i32(flat(&mut s2));
    ct::zeroize_i32(flat(&mut t0));
    ct::zeroize_i32(flat(&mut y));
    ct::zeroize_i32(flat(&mut z));
    ct::zeroize_i32(flat(&mut w));
    ct::zeroize_i32(flat(&mut w1));
    ct::zeroize_i32(&mut cp);
    ct::zeroize_i32(&mut tmp);
    for hi in hint.iter_mut() {
        ct::zeroize(hi);
    }
    sig
}

