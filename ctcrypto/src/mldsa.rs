//! ML-DSA-87 (FIPS 204), constant time.
//!
//! Implemented: the internal interface (Algorithms 6, 7, 8:
//! [`keygen_internal`], [`sign_internal`], [`verify_internal`]), the pure
//! external interface with a context string (Algorithms 2 and 3: [`sign`],
//! [`verify`]) and, sharing the same core, the "external mu" variant in which
//! the caller supplies `mu = H(tr || M', 64)` ([`sign_mu`], [`verify_mu`]).
//!
//! Not implemented: HashML-DSA (the pre-hash variant, Algorithms 4 and 5) and
//! the parameter sets ML-DSA-44/65. The crate has no RNG: the caller supplies
//! the key-generation seed `xi` and the signing randomness `rnd`
//! (`rnd = [0; 32]` gives the deterministic variant of FIPS 204 §3.4).
//!
//! # Constant-time design
//!
//! Secrets are `xi`, `K`, `rho'`, `rho''`, `s1`, `s2`, `t0`, `y`, the secret
//! key bytes, `rnd`, and every intermediate value of a signing attempt until
//! that attempt is accepted. No branch, index, `/` or `%` depends on them:
//! reduction is Montgomery/Barrett-style (`reduce32`), `Power2Round`,
//! `Decompose`, `MakeHint` and the infinity-norm checks are multiply-shift and
//! mask arithmetic built on [`crate::ct`].
//!
//! FIPS 204 itself makes a few one-bit facts about secret data public; each is
//! passed through `ct::declassify*` at exactly one place, marked
//! `DECLASSIFY` in the source:
//!
//! * `ExpandS` (eta = 2) rejection sampling: the accept/reject decision for
//!   each half-byte candidate. This is accepted practice (pqcrystals
//!   reference, TIMECOP): it reveals only how many candidates were rejected
//!   (and where), never an accepted value; the coefficient `2 - (b mod 5)` is
//!   computed with a multiply-shift, not a table or `%`.
//! * The signing loop's four checks (`||z|| < gamma1 - beta`,
//!   `||r0|| < gamma2 - beta`, `||ct0|| < gamma2`, hint weight `<= omega`).
//!   Each is evaluated over the whole vector without early exit and only the
//!   combined bit is declassified; the number of attempts is public by design.
//! * `c_tilde` of every attempt, before `SampleInBall` (which rejection-samples
//!   on it). Standard practice: a rejected attempt's challenge is independent
//!   of the secret key given the abort, and an accepted one is published.
//! * At acceptance, `z` and `h` (published in the signature; hint packing
//!   branches on `h`).
//! * `rho` (public: it is part of the public key) and `t1` (the public key).
//!
//! Verification touches only public data; it branches freely but never panics
//! on malformed input (bad hint encodings and out-of-range `z` return `false`).
//!
//! # Memory
//!
//! No allocation. The 8x7 matrix `A` is never stored: each entry is
//! regenerated by `RejNTTPoly` when it is needed (one 1 KiB polynomial at a
//! time). Signing holds roughly 60 polynomials of 1 KiB plus buffers, so its
//! peak stack is on the order of 70-90 KiB in optimised builds.

use crate::ct;
use crate::sha3::Sponge;

/// Public key length in bytes.
pub const PK_LEN: usize = 2592;
/// Secret key length in bytes.
pub const SK_LEN: usize = 4896;
/// Signature length in bytes.
pub const SIG_LEN: usize = 4627;

const N: usize = 256;
const Q: i32 = 8_380_417;
const QINV: i32 = 58_728_449; // q^-1 mod 2^32
const D: u32 = 13;
const K: usize = 8;
const L: usize = 7;
const ETA: i32 = 2;
const TAU: usize = 60;
const BETA: i32 = 120; // tau * eta
const GAMMA1: i32 = 1 << 19;
const GAMMA2: i32 = (Q - 1) / 32; // 261888
const OMEGA: usize = 75;
const CTILDE_LEN: usize = 64; // lambda / 4

const POLY_T1_LEN: usize = 320; // 10 bits
const POLY_T0_LEN: usize = 416; // 13 bits
const POLY_ETA_LEN: usize = 96; // 3 bits
const POLY_Z_LEN: usize = 640; // 20 bits
const POLY_W1_LEN: usize = 128; // 4 bits

const SK_S1_OFF: usize = 128;
const SK_S2_OFF: usize = SK_S1_OFF + L * POLY_ETA_LEN;
const SK_T0_OFF: usize = SK_S2_OFF + K * POLY_ETA_LEN;
const SIG_Z_OFF: usize = CTILDE_LEN;
const SIG_H_OFF: usize = SIG_Z_OFF + L * POLY_Z_LEN;

const _: () = assert!(32 + K * POLY_T1_LEN == PK_LEN);
const _: () = assert!(SK_T0_OFF + K * POLY_T0_LEN == SK_LEN);
const _: () = assert!(SIG_H_OFF + OMEGA + K == SIG_LEN);

type Poly = [i32; N];

// ---------------------------------------------------------------------------
// Modular arithmetic (all constant time)
// ---------------------------------------------------------------------------

/// Montgomery reduction: for |a| <= 2^31 q returns r = a 2^-32 mod q, |r| < q.
#[inline]
fn mont_reduce(a: i64) -> i32 {
    let t = (a as i32).wrapping_mul(QINV);
    ((a - (t as i64) * (Q as i64)) >> 32) as i32
}

/// For |a| <= 2^31 - 2^22 returns r = a mod q with |r| <= 6291200
/// (|r| < 2^22 + 2^18 for the |a| < 2^28 used here).
#[inline]
fn reduce32(a: i32) -> i32 {
    let t = (a + (1 << 22)) >> 23;
    a - t * Q
}

/// Adds q if a is negative (arithmetic shift, no branch).
#[inline]
fn caddq(a: i32) -> i32 {
    a + ((a >> 31) & Q)
}

/// Canonical representative in [0, q).
#[inline]
fn freeze(a: i32) -> i32 {
    caddq(reduce32(a))
}

/// Algorithm 35 Power2Round for a in [0, q): returns (r1, r0) with
/// a = r1 2^d + r0, r0 in (-2^(d-1), 2^(d-1)].
#[inline]
fn power2round(a: i32) -> (i32, i32) {
    let a1 = (a + (1 << (D - 1)) - 1) >> D;
    (a1, a - (a1 << D))
}

/// Algorithm 36 Decompose for gamma2 = (q-1)/32 and a in [0, q), via the
/// pqcrystals multiply-shift formulas: returns (r1, r0) with r1 in [0, 15]
/// and r0 in (-gamma2, gamma2] (with the q-1 corner case folded in).
#[inline]
fn decompose(a: i32) -> (i32, i32) {
    let mut a1 = (a + 127) >> 7;
    a1 = (a1 * 1025 + (1 << 21)) >> 22;
    a1 &= 15;
    let mut a0 = a - a1 * 2 * GAMMA2;
    a0 -= (((Q - 1) / 2 - a0) >> 31) & Q;
    (a1, a0)
}

/// Algorithm 40 UseHint for a in [0, q) and h in {0, 1}, branch free.
#[inline]
fn use_hint(a: i32, h: u32) -> i32 {
    let (a1, a0) = decompose(a);
    let hm = (h & 1).wrapping_neg();
    // +1 if a0 > 0, else -1
    let pos = ct::mask_lt_i32(0, a0);
    let delta = ct::select_i32(pos, 1, -1);
    ct::select_i32(hm, (a1 + delta) & 15, a1)
}

/// All-ones if |a| >= bound for a centered representative a (|a| < 2^31).
#[inline]
fn mask_abs_ge(a: i32, bound: i32) -> u32 {
    let s = ct::mask_neg_i32(a);
    let abs = ct::select_i32(s, a.wrapping_neg(), a);
    !ct::mask_lt_i32(abs, bound)
}

/// One-bit (0/1) "some coefficient has |a| >= bound", over the whole slice
/// without early exit. The result is still secret; the caller declassifies.
fn norm_exceeds(polys: &[Poly], bound: i32) -> u8 {
    let mut bad = 0u32;
    for p in polys {
        for &c in p.iter() {
            bad |= mask_abs_ge(c, bound);
        }
    }
    (bad & 1) as u8
}

// ---------------------------------------------------------------------------
// NTT (pqcrystals reference schedule; zetas computed at compile time)
// ---------------------------------------------------------------------------

const fn pow_mod(mut b: u64, mut e: u64, m: u64) -> u64 {
    let mut r = 1u64;
    b %= m;
    while e > 0 {
        if e & 1 == 1 {
            r = r * b % m;
        }
        b = b * b % m;
        e >>= 1;
    }
    r
}

/// zetas[i] = 2^32 * 1753^brv8(i) mod q, centered. Public constants.
const ZETAS: [i32; N] = {
    let q = Q as u64;
    let mont = (1u64 << 32) % q;
    let mut z = [0i32; N];
    let mut i = 0;
    while i < N {
        let e = (i as u8).reverse_bits() as u64;
        let v = pow_mod(1753, e, q) * mont % q;
        z[i] = if v > q / 2 { v as i32 - Q } else { v as i32 };
        i += 1;
    }
    z
};

/// Forward NTT, in place, output in bit-reversed order, no final reduction.
/// Input coefficients must satisfy |a| < q (output |a| < 9q).
fn ntt(a: &mut Poly) {
    let mut k = 0;
    let mut len = 128;
    while len > 0 {
        let mut start = 0;
        while start < N {
            k += 1;
            let zeta = ZETAS[k] as i64;
            for j in start..start + len {
                let t = mont_reduce(zeta * a[j + len] as i64);
                a[j + len] = a[j] - t;
                a[j] += t;
            }
            start += 2 * len;
        }
        len >>= 1;
    }
}

/// Inverse NTT with multiplication by the Montgomery factor 2^32.
/// Input |a| < q, output |a| < q.
fn invntt_tomont(a: &mut Poly) {
    const F: i64 = 41_978; // mont^2 / 256
    let mut k = 256;
    let mut len = 1;
    while len < N {
        let mut start = 0;
        while start < N {
            k -= 1;
            let zeta = -(ZETAS[k] as i64);
            for j in start..start + len {
                let t = a[j];
                a[j] = t + a[j + len];
                a[j + len] = t - a[j + len];
                a[j + len] = mont_reduce(zeta * a[j + len] as i64);
            }
            start += 2 * len;
        }
        len <<= 1;
    }
    for c in a.iter_mut() {
        *c = mont_reduce(F * *c as i64);
    }
}

/// out = a o b (pointwise, Montgomery).
#[inline]
fn pointwise(out: &mut Poly, a: &Poly, b: &Poly) {
    for i in 0..N {
        out[i] = mont_reduce(a[i] as i64 * b[i] as i64);
    }
}

