/// Algorithm 21 HintBitUnpack. Returns false on a malformed encoding.
fn hint_unpack(y: &[u8], h: &mut [[u8; N]; K]) -> bool {
    let mut index = 0usize;
    for (i, hi) in h.iter_mut().enumerate() {
        *hi = [0; N];
        let end = y[OMEGA + i] as usize;
        if end < index || end > OMEGA {
            return false;
        }
        let first = index;
        while index < end {
            if index > first && y[index - 1] >= y[index] {
                return false;
            }
            hi[y[index] as usize] = 1;
            index += 1;
        }
    }
    y[index..OMEGA].iter().all(|&b| b == 0)
}

/// z = BitUnpack(.., gamma1 - 1, gamma1) for each polynomial. Returns false
/// if ||z|| >= gamma1 - beta (public data: verification only).
fn unpack_z(sig: &[u8; SIG_LEN], z: &mut [Poly; L]) -> bool {
    let mut ok = true;
    for (j, p) in z.iter_mut().enumerate() {
        let off = SIG_Z_OFF + j * POLY_Z_LEN;
        unpack_poly(&sig[off..off + POLY_Z_LEN], 20, |n, v| {
            let c = GAMMA1 - v as i32;
            ok &= c.abs() < GAMMA1 - BETA;
            p[n] = c;
        });
    }
    ok
}

/// Algorithm 8 ML-DSA.Verify_internal.
pub fn verify_internal(pk: &[u8; PK_LEN], m_prime: &[u8], sig: &[u8; SIG_LEN]) -> bool {
    let mu = compute_mu(&tr_of_pk(pk), &[m_prime]);
    verify_mu(pk, &mu, sig)
}

/// Algorithm 3 ML-DSA.Verify (pure, with context).
///
/// Returns false if `ctx` is longer than 255 bytes. HashML-DSA (pre-hash)
/// is not supported.
pub fn verify(pk: &[u8; PK_LEN], msg: &[u8], ctx: &[u8], sig: &[u8; SIG_LEN]) -> bool {
    if ctx.len() > 255 {
        return false;
    }
    let prefix = [0u8, ctx.len() as u8];
    let mu = compute_mu(&tr_of_pk(pk), &[&prefix, ctx, msg]);
    verify_mu(pk, &mu, sig)
}

/// ML-DSA.Verify_internal with an externally computed
/// `mu = H(H(pk, 64) || M', 64)` ("external mu"). [`verify_internal`] and
/// [`verify`] are wrappers around this core.
pub fn verify_mu(pk: &[u8; PK_LEN], mu: &[u8; 64], sig: &[u8; SIG_LEN]) -> bool {
    let mut rho = [0u8; 32];
    rho.copy_from_slice(&pk[..32]);

    let mut z = [[0i32; N]; L];
    if !unpack_z(sig, &mut z) {
        return false;
    }
    let mut h = [[0u8; N]; K];
    if !hint_unpack(&sig[SIG_H_OFF..], &mut h) {
        return false;
    }
    let mut c_tilde = [0u8; CTILDE_LEN];
    c_tilde.copy_from_slice(&sig[..CTILDE_LEN]);

    let mut cp = [0i32; N];
    sample_in_ball(&mut cp, &c_tilde);
    ntt(&mut cp);
    for p in z.iter_mut() {
        ntt(p);
    }
    let mut w = [[0i32; N]; K];
    matvec(&rho, &z, &mut w);

    let mut t1 = [0i32; N];
    let mut w1 = [[0i32; N]; K];
    for i in 0..K {
        let off = 32 + i * POLY_T1_LEN;
        unpack_poly(&pk[off..off + POLY_T1_LEN], 10, |n, v| t1[n] = (v as i32) << D);
        ntt(&mut t1);
        let mut ct1 = [0i32; N];
        pointwise(&mut ct1, &cp, &t1);
        for n in 0..N {
            w[i][n] = reduce32(w[i][n] - ct1[n]);
        }
        invntt_tomont(&mut w[i]);
        for n in 0..N {
            w1[i][n] = use_hint(freeze(w[i][n]), h[i][n] as u32);
        }
    }
    let mut w1_buf = [0u8; K * POLY_W1_LEN];
    w1_encode(&mut w1_buf, &w1);
    let mut c2 = [0u8; CTILDE_LEN];
    let mut hs = Sponge::shake256();
    hs.absorb(mu);
    hs.absorb(&w1_buf);
    hs.squeeze(&mut c2);
    ct::eq(&c_tilde, &c2) == 0xff
}

