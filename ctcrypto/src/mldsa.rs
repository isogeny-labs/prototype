    /// r mod+- alpha: the representative in (-alpha/2, alpha/2].
    fn mod_pm(r: i64, alpha: i64) -> i64 {
        let mut x = r.rem_euclid(alpha);
        if x > alpha / 2 {
            x -= alpha;
        }
        x
    }

    /// Algorithm 36 as written.
    fn decompose_spec(r: i32) -> (i32, i32) {
        let rp = (r as i64).rem_euclid(Q as i64);
        let mut r0 = mod_pm(rp, 2 * GAMMA2 as i64);
        let r1;
        if rp - r0 == (Q - 1) as i64 {
            r1 = 0;
            r0 -= 1;
        } else {
            r1 = (rp - r0) / (2 * GAMMA2 as i64);
        }
        (r1 as i32, r0 as i32)
    }

    /// Algorithm 35 as written.
    fn power2round_spec(r: i32) -> (i32, i32) {
        let rp = (r as i64).rem_euclid(Q as i64);
        let r0 = mod_pm(rp, 1 << D);
        (((rp - r0) >> D) as i32, r0 as i32)
    }

    /// Algorithm 40 as written (m = 16).
    fn use_hint_spec(h: u32, r: i32) -> i32 {
        let (r1, r0) = decompose_spec(r);
        if h == 1 && r0 > 0 {
            (r1 + 1).rem_euclid(16)
        } else if h == 1 && r0 <= 0 {
            (r1 - 1).rem_euclid(16)
        } else {
            r1
        }
    }

    /// Algorithm 39 as written.
    fn make_hint_spec(z: i32, r: i32) -> u32 {
        let r1 = decompose_spec(r).0;
        let v1 = decompose_spec(((r as i64 + z as i64).rem_euclid(Q as i64)) as i32).0;
        (r1 != v1) as u32
    }

