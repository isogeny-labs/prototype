/// mu = H(tr || parts[0] || parts[1] || ..., 64), absorbing incrementally.
fn compute_mu(tr: &[u8], parts: &[&[u8]]) -> [u8; 64] {
    let mut h = Sponge::shake256();
    h.absorb(tr);
    for p in parts {
        h.absorb(p);
    }
    let mut mu = [0u8; 64];
    h.squeeze(&mut mu);
    mu
}

fn tr_of_pk(pk: &[u8; PK_LEN]) -> [u8; 64] {
    let mut h = Sponge::shake256();
    h.absorb(pk);
    let mut tr = [0u8; 64];
    h.squeeze(&mut tr);
    tr
}

fn flat(v: &mut [Poly]) -> &mut [i32] {
    v.as_flattened_mut()
}

