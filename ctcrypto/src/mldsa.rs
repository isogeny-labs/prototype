/// Algorithm 30 RejNTTPoly on rho || s || r (public data only).
fn rej_ntt_poly(a: &mut Poly, rho: &[u8; 32], s: u8, r: u8) {
    let mut g = Sponge::shake128();
    g.absorb(rho);
    g.absorb(&[s, r]);
    let mut buf = [0u8; 168];
    let mut ctr = 0;
    while ctr < N {
        g.squeeze(&mut buf);
        let mut pos = 0;
        while pos + 3 <= buf.len() && ctr < N {
            let z = (buf[pos] as u32)
                | ((buf[pos + 1] as u32) << 8)
                | (((buf[pos + 2] & 0x7f) as u32) << 16);
            pos += 3;
            if z < Q as u32 {
                a[ctr] = z as i32;
                ctr += 1;
            }
        }
    }
}

/// w = A_hat * v_hat (NTT domain, Montgomery), regenerating A one entry at a
/// time from the public seed `rho` (Algorithm 32 ExpandA, row by row).
fn matvec(rho: &[u8; 32], v: &[Poly; L], w: &mut [Poly; K]) {
    let mut a = [0i32; N];
    let mut t = [0i32; N];
    for (i, wi) in w.iter_mut().enumerate() {
        *wi = [0; N];
        for (j, vj) in v.iter().enumerate() {
            rej_ntt_poly(&mut a, rho, j as u8, i as u8);
            pointwise(&mut t, &a, vj);
            for n in 0..N {
                wi[n] += t[n];
            }
        }
    }
    // `t` held products with secret operands.
    ct::zeroize_i32(&mut t);
}

/// Algorithm 31 RejBoundedPoly for eta = 2, on the secret seed rho' || r.
///
/// The byte stream is secret. The only secret-dependent control flow is the
/// per-candidate accept decision `b < 15`, declassified below: it is the
/// rejection pattern that FIPS 204 sampling inherently has, revealing how
/// many half-bytes were rejected but nothing about accepted values (accepted
/// candidates are uniform on [0, 14] independently of the rejections). The
/// coefficient `2 - (b mod 5)` is computed as `b - floor(205 b / 1024) * 5`,
/// exact for b in [0, 14], with no `%` and no table.
fn rej_bounded_poly(a: &mut Poly, seed: &[u8; 64], r: u16) {
    let mut h = Sponge::shake256();
    h.absorb(seed);
    h.absorb(&r.to_le_bytes());
    let mut buf = [0u8; 136];
    let mut ctr = 0;
    while ctr < N {
        h.squeeze(&mut buf);
        for &byte in buf.iter() {
            let lo = (byte & 15) as u32;
            let hi = (byte >> 4) as u32;
            for b in [lo, hi] {
                if ctr >= N {
                    break;
                }
                let coeff = ETA - (b - ((205 * b) >> 10) * 5) as i32;
                // DECLASSIFY (ExpandS rejection decision): one bit, "this
                // half-byte is < 15". Public by accepted practice; see above.
                let accept = ct::declassify_u8((ct::mask_lt_u32(b, 15) & 1) as u8);
                if accept != 0 {
                    a[ctr] = coeff;
                    ctr += 1;
                }
            }
        }
    }
    ct::zeroize(&mut buf);
}

/// Algorithm 34 ExpandMask: y[r] from rho'' || (kappa + r) (secret output).
fn expand_mask(y: &mut [Poly; L], seed: &[u8; 64], kappa: u16) {
    let mut buf = [0u8; POLY_Z_LEN];
    for (r, yr) in y.iter_mut().enumerate() {
        let mut h = Sponge::shake256();
        h.absorb(seed);
        h.absorb(&kappa.wrapping_add(r as u16).to_le_bytes());
        h.squeeze(&mut buf);
        unpack_poly(&buf, 20, |i, v| yr[i] = GAMMA1 - v as i32);
    }
    ct::zeroize(&mut buf);
}

/// Algorithm 29 SampleInBall on a public (declassified) c_tilde.
fn sample_in_ball(c: &mut Poly, c_tilde: &[u8; CTILDE_LEN]) {
    let mut h = Sponge::shake256();
    h.absorb(c_tilde);
    let mut s = [0u8; 8];
    h.squeeze(&mut s);
    let signs = u64::from_le_bytes(s);
    *c = [0; N];
    for i in (N - TAU)..N {
        let mut j = [0u8; 1];
        loop {
            h.squeeze(&mut j);
            if (j[0] as usize) <= i {
                break;
            }
        }
        let j = j[0] as usize;
        c[i] = c[j];
        c[j] = 1 - 2 * ((signs >> (i + TAU - N)) & 1) as i32;
    }
}

// ---------------------------------------------------------------------------
// Bit packing (loop structure depends only on the public bit width)
// ---------------------------------------------------------------------------

/// Packs 256 values of `bits` bits, little-endian, into `out` (32*bits bytes).
fn pack_poly(out: &mut [u8], bits: u32, f: impl Fn(usize) -> u32) {
    debug_assert_eq!(out.len(), 32 * bits as usize);
    let mut acc: u64 = 0;
    let mut nacc = 0u32;
    let mut o = 0;
    for i in 0..N {
        acc |= ((f(i) & ((1u32 << bits) - 1)) as u64) << nacc;
        nacc += bits;
        while nacc >= 8 {
            out[o] = acc as u8;
            o += 1;
            acc >>= 8;
            nacc -= 8;
        }
    }
    // `acc` may have held secret bits.
    core::hint::black_box(&mut acc);
}

/// Unpacks 256 values of `bits` bits from `inp` (32*bits bytes).
fn unpack_poly(inp: &[u8], bits: u32, mut g: impl FnMut(usize, u32)) {
    debug_assert_eq!(inp.len(), 32 * bits as usize);
    let mut acc: u64 = 0;
    let mut nacc = 0u32;
    let mut p = 0;
    for i in 0..N {
        while nacc < bits {
            acc |= (inp[p] as u64) << nacc;
            p += 1;
            nacc += 8;
        }
        g(i, (acc as u32) & ((1u32 << bits) - 1));
        acc >>= bits;
        nacc -= bits;
    }
}

fn w1_encode(out: &mut [u8; K * POLY_W1_LEN], w1: &[Poly; K]) {
    for (i, p) in w1.iter().enumerate() {
        pack_poly(&mut out[i * POLY_W1_LEN..(i + 1) * POLY_W1_LEN], 4, |n| p[n] as u32);
    }
}

